"""
GET/POST /admin/restaurant/{id}/widget-config (Stage 4 Phase A —
Production Customer Widget). Restaurant-scoped like every other resource
in app/routers/admin.py: reuses get_current_admin + require_restaurant_access,
no new authentication system. widget_key is generated server-side only
— never accepted as input, never regenerated by an update — and is
public (safe to return to any authorized admin caller) but grants no
admin privilege of its own.
"""

from app import models

WIDGET_CONFIG_PUBLIC_FIELDS = {
    "id", "restaurant_id", "widget_key", "welcome_message",
    "primary_language", "logo_url", "accent_color",
    "booking_enabled", "is_active", "created_at", "allowed_origins",
}


def _widget_config_url(restaurant_id):
    return f"/admin/restaurant/{restaurant_id}/widget-config"


