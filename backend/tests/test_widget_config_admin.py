def test_admin_key_never_logged(client, admin_headers, second_restaurant, caplog):
    import logging

    with caplog.at_level(logging.DEBUG):
        client.post(
            _widget_config_url(second_restaurant),
            json={"welcome_message": "hi"},
            headers=admin_headers,
        )

    log_text = "\n".join(record.getMessage() for record in caplog.records)
    assert admin_headers["X-Admin-API-Key"] not in log_text
